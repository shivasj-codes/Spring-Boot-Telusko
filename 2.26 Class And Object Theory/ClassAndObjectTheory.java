/**
 * ============================================================
 * OBJECT-ORIENTED PROGRAMMING (OOP)
 * ============================================================
 *
 * Java is an Object-Oriented Programming language.
 *
 * OOP means:
 *
 * Object-Oriented Programming
 *
 *
 * ============================================================
 * WHAT IS AN OBJECT?
 * ============================================================
 *
 * Real-world things can be considered objects.
 *
 * Examples:
 *
 * Pen
 * Remote
 * Table
 * Human
 *
 * Every object mainly has:
 *
 * 1. Properties -> What it KNOWS
 * 2. Behaviors -> What it DOES
 *
 *
 * ============================================================
 * PROPERTIES AND BEHAVIORS
 * ============================================================
 *
 * Example: PEN
 *
 * Properties:
 *
 * Color
 * Brand
 * Height
 *
 * Behavior:
 *
 * Writing
 *
 *
 * Example: HUMAN
 *
 * Properties:
 *
 * Name
 * Age
 *
 * Behaviors:
 *
 * Walking
 * Talking
 * Dancing
 *
 *
 * Easy way to remember:
 *
 * What an object KNOWS -> Properties
 *
 * What an object DOES -> Behaviors
 *
 *
 * ============================================================
 * CLASS AND OBJECT
 * ============================================================
 *
 * To create an object in Java, we first need a CLASS.
 *
 * A class is a BLUEPRINT or DESIGN.
 *
 * Example:
 *
 * Class -> Blueprint of a table
 *
 * Object -> Actual table
 *
 *
 * Simple flow:
 *
 * CLASS
 * ↓
 * OBJECT
 *
 *
 * ============================================================
 * BASIC IDEA
 * ============================================================
 *
 * OBJECT
 * |
 * |--> Properties
 * |
 * |--> Behaviors
 *
 *
 * CLASS
 * ↓
 * Blueprint
 * ↓
 * OBJECT
 *
 *
 * ============================================================
 * KEY POINTS
 * ============================================================
 *
 * 1. Java supports Object-Oriented Programming (OOP).
 *
 * 2. Objects have properties and behaviors.
 *
 * 3. Properties = What an object knows.
 *
 * 4. Behaviors = What an object does.
 *
 * 5. A class is a blueprint.
 *
 * 6. An object is created from a class.
 *
 * ============================================================
 */
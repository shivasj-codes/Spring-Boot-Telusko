public class NeedOfArray {

    // A normal variable can store only one value.
    int i = 5;

    // Another normal variable stores another value.
    int j = 6;

    int k = 7;

    // An array can store multiple values in one variable.
    // [] indicates that num is an array.
    int num[] = { 5, 6, 7 };

    // If the values are not known initially,
    // create an integer array with space for 4 values.
    // new -> Creates a new array.
    // int[4] -> The array size is 4.
    //
    // IMPORTANT:
    // Once the array size is defined, its size is fixed.
    int num1[] = new int[4];

}